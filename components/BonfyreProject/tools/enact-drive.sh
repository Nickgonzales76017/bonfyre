#!/bin/sh
# Record the native protocol owner's enactment of a previously observed read.
# No request is sent and no authority is granted here. The retained receipt must
# record policy allow, an attempted successful HTTP 200 transport, and a body
# whose digest still matches. Only source-shape read relations are selected.
#
# ACTOR is the caller's assertion: current ForeignTwin receipts do not retain
# the observer identity. A robots decision is not a legal conclusion, current
# permission, or a licence to republish. Native --evidence-stands/--discharge
# record the local claim; they do not mean the source agreed. Native DB writes
# and evidence-file writes are not one transactional operation.
set -eu
root=$(CDPATH= cd -- "$(dirname -- "$0")/../../.." && pwd -P)
cd "$root"
sweep=${1:-$HOME/.bonfyre/foreign-sweep}
out=${2:-$HOME/.bonfyre/estate/enactment-evidence.jsonl}
db=${ENACT_DB:-$HOME/.bonfyre/estate/enactment.db}
corpus=${CORPUS:-$root/estate/generated/external-estate-v4/observed-external-estate.jsonl}
actor=${ACTOR:-BonfyreProject/1.0}
facet="$root/cmd/BonfyreFacet/bonfyre-facet"
lex="$root/cmd/BonfyreLex/bonfyre-lex"
if [ ! -x "$facet" ] || [ ! -x "$lex" ]; then
  echo 'read enactment drive: native facet and lex executables required' >&2
  exit 1
fi
command -v bun >/dev/null
helper="$root/components/BonfyreProject/tools/read-protocol-contract.mjs"
bun "$helper" owner-values "$corpus" "$db" "$actor" "$out"
work=$(mktemp -d "${TMPDIR:-/tmp}/bonfyre-read-drive.XXXXXX")
trap 'rm -f "$work/compiled.json"; rmdir "$work"' EXIT
trap 'exit 129' HUP
trap 'exit 130' INT
trap 'exit 143' TERM
: > "$out"
compile_failed=0 invalid_compiler=0

enacted=0 refused=0 unpermitted=0 drifted=0 considered=0
for receipt in "$sweep"/receipts/*.json; do
  [ -f "$receipt" ] || continue
  oid=$("$lex" field --kind json_string --key twin_id --line last --file "$receipt" 2>/dev/null) || continue
  case "$oid" in external:*) ;; *) continue ;; esac
  bun "$helper" owner-values "$oid" >/dev/null 2>&1 || { refused=$((refused + 1)); continue; }

  # A retained allow decision is required, not generated by this driver.
  # It is evidence of the observer's policy decision, not a legal finding.
  decision=$("$lex" field --kind json_string --key policy_decision --line last --file "$receipt" 2>/dev/null) || decision=''
  status=$("$lex" field --kind json_number --key http_status --line last --file "$receipt" 2>/dev/null) || status=''
  attempted=$("$lex" field --kind json_bool --key fetch_attempted --line last --file "$receipt" 2>/dev/null) || attempted=''
  transport=$("$lex" field --kind json_number --key transport_exit --line last --file "$receipt" 2>/dev/null) || transport=''
  [ "$decision" = "allow" ] && [ "$status" = "200" ] && [ "$attempted" = "true" ] && [ "$transport" = "0" ] || { unpermitted=$((unpermitted+1)); continue; }

  body=$("$lex" field --kind json_string --key body_path --line last --file "$receipt" 2>/dev/null) || continue
  digest=$("$lex" field --kind json_string --key content_sha256 --line last --file "$receipt" 2>/dev/null) || continue
  [ -n "$body" ] && [ -f "$body" ] || { unpermitted=$((unpermitted+1)); continue; }

  # The bytes must still be the bytes the permission was exercised over.
  have=$(shasum -a 256 "$body" 2>/dev/null | cut -d' ' -f1)
  [ "$have" = "$digest" ] || { drifted=$((drifted+1)); continue; }
  considered=$((considered + 1))

  # Do not let a parseable stdout hide a failed native compilation.
  if ! "$facet" compile --corpus "$corpus" --occurrence "$oid" >"$work/compiled.json" 2>/dev/null; then
    compile_failed=$((compile_failed + 1)); refused=$((refused + 1)); continue
  fi
  pick_status=0
  pick=$(bun "$helper" pick "$work/compiled.json" 2>/dev/null) || pick_status=$?
  if [ "$pick_status" -ne 0 ]; then
    [ "$pick_status" -eq 4 ] || invalid_compiler=$((invalid_compiler + 1))
    refused=$((refused + 1)); continue
  fi
  [ -n "$pick" ] || { refused=$((refused + 1)); continue; }
  proto=${pick%% *}
  rel=${pick##* }
  at=$("$lex" field --kind json_string --key observed_at --line last --file "$receipt" 2>/dev/null) || at=''
  [ -n "$at" ] || { refused=$((refused+1)); continue; }
  bun "$helper" owner-values "$at" >/dev/null 2>&1 || { refused=$((refused + 1)); continue; }

  # No authority is granted here, by anyone, to anyone. A read of a public
  # representation requires none in its relation shape -- the enactment reports
  # authority_required false -- so the flag that would grant one is not passed
  # and could not be the reason this closes. The only permission in play is the
  # source's, exercised at request time and checked above.
  #
  # These flags assert the local evidence/obligation claim to its native owner.
  # That owner currently accepts no --receipt for enact: this wrapper's checks
  # are not a cryptographic receipt binding or agreement from the source.
  if "$facet" enact --corpus "$corpus" --occurrence "$oid" --protocol "$proto" \
       --relation "$rel" --db "$db" --actor "$actor" --subject "$oid" --at "$at" \
       --evidence-stands --discharge --out "$out" >/dev/null 2>&1; then
    enacted=$((enacted + 1))
  else
    refused=$((refused + 1))
  fi
done

bun "$helper" enact-summary "$considered" "$enacted" "$refused" "$unpermitted" "$drifted" "$compile_failed" "$invalid_compiler" "$actor"
