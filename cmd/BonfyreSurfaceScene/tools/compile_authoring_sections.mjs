// Single-source manifest compiler for ALL first-party ServiceSite section owners.
// A section added, removed, or edited is a mandatory JS/native grammar change.
import {readdirSync,readFileSync,writeFileSync} from "node:fs";
import {createHash} from "node:crypto";
import {join} from "node:path";
import {fileURLToPath} from "node:url";
const root=fileURLToPath(new URL("../../../components/BonfyreServiceSite/sections/",import.meta.url));
const js=fileURLToPath(new URL("../../../components/BonfyreServiceSite/authoring/site-section-catalogue.generated.mjs",import.meta.url));
const header=fileURLToPath(new URL("../../BonfyreWebAddress/generated/native_site_section_catalogue.h",import.meta.url));
export function collectSectionCatalogue(){
 const files=readdirSync(root).filter(name=>/^[a-z][a-z0-9-]*\.mjs$/.test(name)).sort();
 return files.map(file=>{
  const source=readFileSync(join(root,file));
  const code=source.toString("utf8");
  const needs=code.match(/\bexport\s+const\s+needs\s*=\s*\[([^\]]*)\]/);
  if(!needs)throw Error("Section "+file+" is missing a static required-field contract");
  const raw=needs[1].trim().replace(/(['"])[a-z][\w-]*\1\s*,?/g,"");
  if(raw.trim())throw Error("Unrecognized required fields in "+file);
  const required=[...needs[1].matchAll(/['"]([a-z][a-z0-9_-]*)['"]/g)].map(x=>x[1]);
  if(new Set(required).size!==required.length)throw Error("Repeated required field "+file);
  return {kind:file.slice(0,-4),required,sha256:createHash("sha256").update(source).digest("hex")};
 });
}
export function compileSectionCatalogue(rows=collectSectionCatalogue()){
 const jsText="/* bonfyre:generated by compile_authoring_sections.mjs; source modules retain behavior. */\n"+
   "export const SITE_SECTION_CATALOGUE = Object.freeze("+JSON.stringify(rows,null,2)+
   ".map(row=>Object.freeze({...row,required:Object.freeze(row.required)})));\n";
 const cText="/* Generated from sections/*.mjs. This registry is not a publication right. */\n"+
   "#ifndef BF_NATIVE_SITE_SECTION_CATALOGUE_H\n#define BF_NATIVE_SITE_SECTION_CATALOGUE_H\n"+
   "#include <stddef.h>\n#include <string.h>\n"+
   "typedef struct {const char *kind;const char *required;const char *source_digest;} BfNativeSection;\n"+
   "static const BfNativeSection bf_native_sections[] = {\n"+
   rows.map(x=>'    {"'+x.kind+'","'+x.required.join(",")+'","'+x.sha256+'"},').join("\n")+
   "\n};\n#define BF_NATIVE_SECTION_COUNT (sizeof(bf_native_sections)/sizeof(bf_native_sections[0]))\n"+
   "static inline const BfNativeSection *bf_native_section(const char *kind) {\n"+
   " if(!kind)return NULL;\n"+
   " for(size_t i=0;i<BF_NATIVE_SECTION_COUNT;i++)if(!strcmp(bf_native_sections[i].kind,kind))return &bf_native_sections[i];\n"+
   " return NULL;\n}\n#endif\n";
 return {jsText,cText};
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
 const flag=process.argv[2],{jsText,cText}=compileSectionCatalogue();
 if(flag==="--write"){
  writeFileSync(js,jsText);writeFileSync(header,cText);
  console.log("Section registry generated",collectSectionCatalogue().length);
 }else if(flag==="--check"){
  if(readFileSync(js,"utf8")!==jsText||readFileSync(header,"utf8")!==cText)throw Error("Section registry needs regeneration");
  console.log("Section registry JS/native parity PASS",collectSectionCatalogue().length);
 }else {console.error("usage: node compile_authoring_sections.mjs --check|--write");process.exit(2);}
}
