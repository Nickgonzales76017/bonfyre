#ifndef BONFYRE_PROFILE_JOURNAL_BATCH_H
#define BONFYRE_PROFILE_JOURNAL_BATCH_H
#include "ui_tree.h"
/* Private editorial release orchestration: no new publication authority.
 * Each selected exact route is independently reviewed and committed through
 * the existing CMS page-release action with owner/CSRF/version gates. A
 * rejected or uncertain result never becomes "published" in this UI until
 * the native CMS readback confirms it. */
static void ph_journal_batch_script(void){
 ui_script(stdout,"\n"
 "(()=>{\n"
 "for(const root of document.querySelectorAll('[data-profile-journal]')){\n"
 " const bar=root.querySelector('[data-journal-batch]');\n"
 " if(!bar)return;\n"
 " const site=bar.dataset.site;\n"
 " const selectAll=bar.querySelector('[data-journal-select-all]');\n"
 " const clear=bar.querySelector('[data-journal-clear]');\n"
 " const rights=bar.querySelector('[data-journal-rights]');\n"
 " const publish=bar.querySelector('[data-journal-publish]');\n"
 " const status=bar.querySelector('[data-journal-status]');\n"
 " let busy=false;\n"
 " const cards=()=>[...root.querySelectorAll('[data-journal-route]')].filter(x=>x.dataset.publicationState==='draft'&&!x.dataset.released);\n"
 " if(!cards().length){bar.hidden=true;continue;}\n"
 " const chosen=()=>cards().filter(x=>x.querySelector('[data-journal-select]')?.checked);\n"
 " const update=()=>{\n"
 "  const n=chosen().length;\n"
 "  publish.disabled=busy||!rights.checked||!n;\n"
 "  selectAll.disabled=busy;clear.disabled=busy;rights.disabled=busy;\n"
 "  status.textContent=busy?'Publishing selected saved revisions...':n+' draft'+(n===1?'':'s')+' selected for review';\n"
 " };\n"
 " selectAll.addEventListener('click',()=>{for(const c of cards())if(!c.hidden)c.querySelector('[data-journal-select]').checked=true;update();});\n"
 " clear.addEventListener('click',()=>{for(const c of cards())c.querySelector('[data-journal-select]').checked=false;rights.checked=false;update();});\n"
 " rights.addEventListener('change',update);\n"
 " root.addEventListener('change',event=>{if(event.target.matches('[data-journal-select]'))update();});\n"
 " const path=(route,publish=false)=>'/cms/compose/'+(publish?'publish':'page')+'?site='+encodeURIComponent(site)+'&route='+encodeURIComponent(route);\n"
 " async function exact(url,options){\n"
 "  const response=await fetch(url,{credentials:'same-origin',cache:'no-store',...options});\n"
 "  const data=await response.json().catch(()=>({}));\n"
 "  if(!response.ok)throw Error(data.error||'CMS refused the requested revision');\n"
 "  return data;\n"
 " }\n"
 " publish.addEventListener('click',async()=>{\n"
 "  if(busy||!rights.checked)return;\n"
 "  const queue=chosen();\n"
 "  if(!queue.length)return;\n"
 "  busy=true;update();let done=0;const blocked=[];\n"
 "  for(const card of queue){\n"
 "   const route=card.dataset.journalRoute;\n"
 "   if(!/^\\/blog\\/[a-z0-9-]+\\/$/.test(route)){blocked.push('Invalid article address');continue;}\n"
 "   try{\n"
 "    const current=await exact(path(route));\n"
 "    if(current.snapshot?.page?.status!=='draft'||!Number.isSafeInteger(current.id)||current.id<1||!/^[a-f0-9]{64}$/.test(current.digest))throw Error('Reopen the saved draft for review');\n"
 "    const payload={expected_id:current.id,expected_digest:current.digest,rights_confirmed:true};\n"
 "    try{\n"
 "     const result=await exact(path(route,true),{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(payload)});\n"
 "     if(result.committed!==true||result.id!==current.id)throw Error('Publication was not confirmed');\n"
 "    }catch(error){\n"
 "     const after=await exact(path(route));\n"
 "     if(after.snapshot?.page?.status!=='published')throw error;\n"
 "    }\n"
 "    card.dataset.released='1';card.querySelector('[data-journal-select]').checked=false;done++;\n"
 "    root.dispatchEvent(new Event('journalchange'));\n"
 "   }catch(error){blocked.push(route+': '+String(error.message||error));}\n"
 "  }\n"
 "  busy=false;rights.checked=false;update();\n"
 "  status.textContent=done+' published'+(blocked.length?'; '+blocked.length+' held for review. '+blocked.slice(0,2).join(' | '):'. Refresh to see the published journal.');\n"
 " });\n"
 " update();\n"
 "}\n"
 "})();\n");
 fputc('\n',stdout);
}
#endif
