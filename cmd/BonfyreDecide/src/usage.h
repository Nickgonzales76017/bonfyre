    "bonfyre manifest — an itemised manifest for an equipment lot, from its photos and listing\n"
    "\n"
    "Usage:\n"
    "  bonfyre manifest [--lot NAME] --photo FILE [--photo FILE ...] [--listing FILE ...] [options]\n"
    "\n"
    "Every photo is read on this machine; photos named alike (lot-1.jpg, lot-2.jpg)\n"
    "are one view. Brand, model family, part number, count and the listing's own\n"
    "condition and make are copied as written. The local model then says what kind\n"
    "of equipment each unit is, whether it holds data to wipe, whether make and\n"
    "model are clear enough to price, and what the text says about condition.\n"
    "Anything the seller did not state is left blank and listed to confirm.\n"
    "\n"
    "Options:\n"
    "  --photo FILE      A photo of the lot (repeat)\n"
    "  --listing FILE    The seller's listing, saved as HTML or text (repeat)\n"
    "  --lot NAME        A name for the lot\n"
    "  --out FILE        The manifest as TSV, or the full report with receipts (.json)\n"
    "  --itad FILE       A TSV the ITAD Exchange desk imports (model, qty, grade);\n"
    "                    units it cannot price yet go to FILE.held.tsv with the reason\n"
    "  --json            Print the full report\n"
    "  --model NAME        Prefer this local model (a file name or part of one);\n"
    "                      otherwise the front loads the largest that fits\n"
    "  --model-endpoint U  Local model server (default http://127.0.0.1:7000)\n"
    "\n"
    "Example:\n"
    "  bonfyre manifest --lot houston-35 --photo houston-35-1.jpg --photo houston-35-2.jpg --out houston-35.tsv\n";
