#!/bin/sh
# Native ratchet: measure the JS estate and installed programs, and refuse any
# change that makes them worse than architecture/native-ratchet.cue allows.
#
#   scripts/native-ratchet.sh measure    print the measurement as JSON
#   scripts/native-ratchet.sh check      fail if any figure exceeds its budget
#   scripts/native-ratchet.sh tighten    lower budgets to the current figures
#   scripts/native-ratchet.sh top        list the largest currently counted MJS files
#
# BONFYRE_BIN (default ~/.bonfyre/bin) adds the installed-program figures when
# that directory exists; CI has none and checks only the tree.
set -eu
root=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)
law="$root/architecture/native-ratchet.cue"
bin=${BONFYRE_BIN:-"$HOME/.bonfyre/bin"}

browser_projection_parity() {
  # Extension packaging is generated from these exact canonical browser owners.
  # Do not forgive a stale or altered projection merely to pass a line budget.
  for name in recurring-commerce contents; do
    source="$root/scripts/recurring-commerce/$name.mjs"
    [ "$name" = recurring-commerce ] && source="$root/scripts/recurring-commerce/draft.mjs"
    target="$root/integrations/browser/extension/$name.mjs"
    if ! cmp -s "$source" "$target"; then
      echo "native ratchet: browser projection drift ($name)" >&2; return 1
    fi
  done
  for name in workspace-msgpack provider-contract; do
    source="$root/integrations/browser/$name.mjs"
    target="$root/integrations/browser/extension/$name.mjs"
    if ! { printf "%s\n" "// Generated by scripts/project-provider-work-browser.mjs; edit the canonical browser module."; cat "$source"; } | cmp -s - "$target"; then
      echo "native ratchet: browser projection drift ($name)" >&2; return 1
    fi
  done
}

authored() {
  browser_projection_parity || return 1
  # WebAddress projects these two browser assets byte-for-byte from the
  # BonfyreSurfaceScene canonical sources and page_surface_scene_test.sh cmp's
  # both pairs. Count the owner once, not the generated serving copies.
  # Program service policy is likewise a generated projection of program-fabric.cue;
  # project-program-service-policy.mjs --check and rollout acceptance require exact
  # generated bytes, so count its CUE/generator owners rather than the projection.
  git -C "$root" ls-files -co --exclude-standard -z -- '*.mjs' |
    tr '\0' '\n' |
    grep -v -E '(^|/)(node_modules|vendor)/|^site/matrix/(bonfyre-surface-runtime|bonfyre-workspace-composition)\.mjs|^integrations/browser/program-service-policy\.mjs$|^integrations/browser/extension/(recurring-commerce|contents|workspace-msgpack|provider-contract)\.mjs$' |
    while IFS= read -r path; do
      if [ -f "$root/$path" ]; then printf '%s\n' "$path"; fi
    done
}

measure() {
  list=$(authored)
  files=$(printf '%s\n' "$list" | grep -c . || true)
  lines=$(cd "$root" && printf '%s\n' "$list" | grep . | tr '\n' '\0' | xargs -0 cat 2>/dev/null | wc -l | tr -d ' ')
  sites=$(cd "$root" && git ls-files -co --exclude-standard -z -- '*.sh' '*.mjs' 'Makefile' '*/Makefile' '*.mk' |
    tr '\0' '\n' | grep -v -E '(^|/)node_modules/|^scripts/native-ratchet\.sh$' | tr '\n' '\0' |
    xargs -0 grep -l -E '^[^#/]*(bun|BUN\)) +build .*--compile' 2>/dev/null | grep -c . || true)
  other=$(git -C "$root" ls-files -co --exclude-standard -- '*.js' '*.cjs' '*.ts' '*.tsx' '*.py' |
    grep -v -E '(^|/)(node_modules|vendor)/' |
    while IFS= read -r path; do
      if [ -f "$root/$path" ]; then printf '%s\n' "$path"; fi
    done | grep -c . || true)
  printf '{"authored_mjs_files":%s,"authored_mjs_lines":%s,"other_script_files":%s,"bun_compile_sites":%s' "$files" "$lines" "$other" "$sites"
  if [ -d "$bin" ]; then
    js=0; big=0; total=0; seen=" "
    for f in "$bin"/bonfyre*; do
      [ -f "$f" ] && [ -x "$f" ] && [ ! -L "$f" ] || continue
      inode=$(ls -i "$f" | awk '{print $1}')
      case "$seen" in *" $inode "*) continue ;; esac
      seen="$seen$inode "
      size=$(wc -c < "$f" | tr -d ' ')
      total=$((total + size))
      [ "$size" -gt "$big" ] && big=$size
      if [ "$size" -gt 4000000 ] && LC_ALL=C grep -q -a 'bun create' "$f"; then js=$((js + 1)); fi
    done
    printf ',"js_runtime_bins":%s,"largest_bin_bytes":%s,"installed_bonfyre_bytes":%s' "$js" "$big" "$total"
  fi
  printf '}\n'
}

case "${1:-check}" in
  measure) measure ;;
  check)
    m=$(measure)
    if ! printf '%s' "$m" | cue vet -d '#Measure' "$law" json: - 2>/tmp/native-ratchet.$$; then
      echo "native ratchet: a figure got worse than its budget" >&2
      echo "  measured: $m" >&2
      sed 's/^/  /' /tmp/native-ratchet.$$ >&2
      rm -f /tmp/native-ratchet.$$
      echo "  budgets: architecture/native-ratchet.cue; plan: docs/engineering/mjs-retirement-20261022/PLAN.md" >&2
      exit 1
    fi
    rm -f /tmp/native-ratchet.$$
    echo "native ratchet: ok $m" ;;
  top)
    authored | while IFS= read -r p; do
      [ -f "$root/$p" ] || continue
      n=$(wc -l < "$root/$p" | tr -d ' ')
      printf '%s\t%s\n' "$n" "$p"
    done | LC_ALL=C sort -nr | head -n 120 ;;
  tighten)
    m=$(measure)
    for k in authored_mjs_files authored_mjs_lines other_script_files bun_compile_sites js_runtime_bins largest_bin_bytes installed_bonfyre_bytes; do
      v=$(printf '%s' "$m" | sed -n "s/.*\"$k\":\([0-9]*\).*/\1/p")
      [ -n "$v" ] || continue
      cur=$(sed -n "s/^[[:space:]]*$k: *\([0-9_]*\).*/\1/p" "$law" | tr -d _)
      if [ -n "$cur" ] && [ "$v" -lt "$cur" ]; then
        sed -E "s/^([[:space:]]*$k: *)[0-9_]+/\1$v/" "$law" > "$law.$$" && mv "$law.$$" "$law"
        echo "tightened $k: $cur -> $v"
      fi
    done ;;
  *) echo "usage: $0 measure|check|top|tighten" >&2; exit 2 ;;
esac
