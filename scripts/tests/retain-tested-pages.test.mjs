import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {execFileSync} from 'node:child_process';
import {retainRelease} from '../retain-tested-pages.mjs';

function fixture() {
  const home = mkdtempSync(join(tmpdir(), 'pages-retention-'));
  const remote = join(home, 'remote'), one = join(home, 'one'), two = join(home, 'two');
  const git = (cwd, ...args) => execFileSync('git', args, {cwd, encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe']}).trim();
  git(home, 'init', '--bare', '--initial-branch=main', remote);
  git(home, 'clone', remote, one);
  const identity = cwd => {git(cwd, 'config', 'user.name', 'Release Test'); git(cwd, 'config', 'user.email', 'release@example.test');};
  identity(one); mkdirSync(join(one, 'site'));
  writeFileSync(join(one, 'source.txt'), 'one'); writeFileSync(join(one, 'site/index.txt'), 'one');
  git(one, 'add', '.'); git(one, 'commit', '-m', 'Initial source'); git(one, 'push', 'origin', 'main');
  git(home, 'clone', remote, two); identity(two);
  const change = (path, value) => {git(two, 'pull', '--ff-only'); writeFileSync(join(two, path), value); git(two, 'add', path); git(two, 'commit', '-m', 'Concurrent source'); git(two, 'push', 'origin', 'main');};
  const current = path => git(remote, 'show', 'main:' + path);
  let verified = 0;
  const verify = () => {verified++; const source=readFileSync(join(one,'source.txt'),'utf8'); if(source==='bad')throw Error('Invalid new source'); writeFileSync(join(one,'site/index.txt'),source);};
  return {home, one, two, remote, git, change, current, verify, verified:()=>verified, cleanup:()=>rmSync(home,{recursive:true,force:true})};
}
function scenario(name, fn) {test(name,()=>{const f=fixture();try{fn(f);}finally{f.cleanup();}});}
const run = (f, extra={}) => retainRelease({cwd:f.one,paths:['site'],verify:f.verify,...extra});
scenario('ordinary verified projection is retained without an empty commit',f=>{
 const before=f.git(f.remote,'rev-parse','main'),r=run(f);assert.equal(r.head,before);assert.equal(f.verified(),1);
});
scenario('a generated update is retained from its tested source',f=>{
 writeFileSync(join(f.one,'source.txt'),'two');f.git(f.one,'add','source.txt');f.git(f.one,'commit','-m','Updated source');
 const r=run(f);assert.equal(f.current('site/index.txt'),'two');assert.equal(f.current('source.txt'),'two');assert.equal(r.attempts,1);
});
scenario('concurrent unrelated source is preserved and the release is reverified',f=>{
 const r=run(f,{beforePush:n=>{if(n===1)f.change('note.txt','independent work');}});
 assert.equal(r.attempts,2);assert.equal(f.current('note.txt'),'independent work');assert.equal(f.verified(),2);
});
scenario('concurrent build input is rebuilt instead of deploying stale generated bytes',f=>{
 const r=run(f,{beforePush:n=>{if(n===1)f.change('source.txt','new upstream');}});
 assert.equal(r.attempts,2);assert.equal(f.current('site/index.txt'),'new upstream');assert.equal(f.verified(),2);
});
scenario('a reconciliation that fails verification never reaches the remote release',f=>{
 assert.throws(()=>run(f,{beforePush:n=>{if(n===1)f.change('source.txt','bad');}}),/Invalid new source/);
 assert.equal(f.current('source.txt'),'bad');assert.equal(f.current('site/index.txt'),'one');
});
scenario('a real generated-file conflict aborts without overwriting upstream',f=>{
 const verify=()=>writeFileSync(join(f.one,'site/index.txt'),'our generated page');
 assert.throws(()=>run(f,{verify,beforePush:n=>{if(n===1)f.change('site/index.txt','their different page');}}),/conflict/);
 assert.equal(f.current('site/index.txt'),'their different page');assert.equal(f.git(f.one,'symbolic-ref','--short','HEAD'),'main');
});
scenario('unrelated staged work is never included in a release commit',f=>{
 writeFileSync(join(f.one,'source.txt'),'staged work');f.git(f.one,'add','source.txt');
 assert.throws(()=>run(f),/Unrelated staged work/);assert.equal(f.current('source.txt'),'one');assert.equal(f.verified(),0);
});
scenario('lost successful push response is recovered by exact remote-head readback',f=>{
 const r=run(f,{pushResult:git=>{git(['push','origin','HEAD:main']);return {status:1,stderr:'Lost response'};}});
 assert.equal(r.recovered,true);assert.equal(f.verified(),1);
});
scenario('continuous concurrent changes have a bounded retry count',f=>{
 assert.throws(()=>run(f,{beforePush:n=>f.change('note.txt','revision '+n)}),/exhausted/);
 assert.equal(f.verified(),3);assert.equal(f.current('note.txt'),'revision 3');
});
