import {readFile,writeFile,mkdir,copyFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {join,resolve} from 'node:path';
import {execFileSync} from 'node:child_process';
import {replaceSpacesComponents} from './component-release.mjs';
const source=resolve(process.env.WORKSPACE_INPUTS??'workspace-inputs'),dest=resolve('site/spaces/assets/workspace-docking');
await mkdir(dest,{recursive:true});await mkdir('workspace-evidence',{recursive:true});
const pack=await readFile(join(source,'dockview-core-8.5.1.tgz')),integrity=(await readFile(join(source,'dockview-core.integrity'),'utf8')).trim();
if('sha512-'+createHash('sha512').update(pack).digest('base64')!==integrity)throw Error('Dockview archive does not match retained registry integrity.');
const temp=resolve('.workspace-extracted');await mkdir(temp,{recursive:true});
execFileSync('tar',['-xzf',join(source,'dockview-core-8.5.1.tgz'),'-C',temp]);
await copyFile(join(temp,'package/dist/package/main.esm.mjs'),join(dest,'dockview-8.5.1.mjs'));
const freeArchive=await readFile(join(source,'dockview-8.5.1.tgz')),freeIntegrity=(await readFile(join(source,'dockview.integrity'),'utf8')).trim();
if('sha512-'+createHash('sha512').update(freeArchive).digest('base64')!==freeIntegrity)throw Error('Dockview entry archive integrity mismatch.');
const entry=resolve('.workspace-entry');await mkdir(entry,{recursive:true});execFileSync('tar',['-xzf',join(source,'dockview-8.5.1.tgz'),'-C',entry]);
await copyFile(join(entry,'package/dist/styles/dockview.css'),join(dest,'dockview-8.5.1.css'));
await copyFile(join(temp,'package/LICENCE.md'),join(dest,'LICENSE.md'));
await writeFile(join(dest,'SOURCE.txt'),`dockview-core 8.5.1\nhttps://registry.npmjs.org/dockview-core/-/dockview-core-8.5.1.tgz\n${integrity}\nOnly MIT core docking is used. No enterprise modules or layout record store.\n`);
await replaceSpacesComponents('site/spaces');
await writeFile('workspace-evidence/BUILD.txt','Built existing catalogue and planner from shared workspace composition.\n');
