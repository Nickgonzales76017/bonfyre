// The extension package cannot import outside its root. Keep these two pure
// browser modules exact projections of their existing canonical native source.
import {readFile,writeFile} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const args=process.argv.slice(2);if(args.some(a=>!['--check','--write'].includes(a))||args.length>1)throw Error('Use --check or --write.');
for(const name of ['workspace-msgpack.mjs','provider-contract.mjs']){
 const source=await readFile(resolve(root,'integrations/browser',name),'utf8');
 const path=resolve(root,'integrations/browser/extension',name),projected='// Generated by scripts/project-provider-work-browser.mjs; edit the canonical browser module.\n'+source;
 if(args[0]==='--check'){if(await readFile(path,'utf8')!==projected)throw Error('Regenerate '+name+' with scripts/project-provider-work-browser.mjs --write.');}
 else await writeFile(path,projected);
}
